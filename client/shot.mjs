import { chromium } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push(e.message.slice(0, 160)));
page.on('console', m => { if (m.type()==='error') errs.push('CONSOLE: '+m.text().slice(0,160)); });
await page.goto('https://spotibet.onrender.com', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(6000);
console.log('TITLE:', await page.title());
console.log('BODY:', (await page.locator('body').innerText()).replace(/\s+/g,' ').slice(0,250));
const av = page.getByText('Aviator', { exact: true }).first();
console.log('AV_COUNT:', await av.count());
await av.click({ timeout: 20000 }).catch(e=>console.log('CLICK_ERR', e.message.slice(0,100)));
await page.waitForTimeout(6000);
console.log('AFTER_BODY:', (await page.locator('body').innerText()).replace(/\s+/g,' ').slice(0,300));
console.log('CANVAS:', await page.locator('canvas').count());
console.log('ERRS:', JSON.stringify(errs.slice(0,6)));
await page.screenshot({ path: 'C:\\Users\\kariu\\AppData\\Local\\Temp\\opencode\\render-live.png' });
await ctx.close(); await browser.close();
